// Renders the printable parts from hardware/bat-handle/bat_handle.scad,
// converts them to binary STL, and writes src/bat/mountProfile.json from the
// MOUNT_JSON line that OpenSCAD echoes. That keeps the game's bat geometry
// in sync with the printed part.
//
// Usage: npm run export-stl [-- -D grip_depth_low=38 ...]
// Needs OpenSCAD on PATH (2021.01 or newer).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const scad = join(root, 'hardware/bat-handle/bat_handle.scad');
const stlDir = join(root, 'hardware/bat-handle/stl');
const cacheDir = join(root, 'tools/.render-cache');
// Extra OpenSCAD overrides, e.g. `npm run export-stl -- grip_depth_low=38`
const defs = process.argv.slice(2).filter((d) => d !== '-D').flatMap((d) => ['-D', d]);

const parts = [
  { part: 'body', out: join(stlDir, 'bat_handle_body.stl') },
  { part: 'fit_test', out: join(stlDir, 'fit_test_rings.stl') },
  // Render-only meshes (controller stand-ins and straps) for the design sheet
  { part: 'proxy_right', out: join(cacheDir, 'proxy_right.stl') },
  { part: 'proxy_right_controls', out: join(cacheDir, 'proxy_right_controls.stl') },
  { part: 'strap_bands', out: join(cacheDir, 'strap_bands.stl') },
];

const only = process.env.PARTS ? process.env.PARTS.split(',') : null;
mkdirSync(stlDir, { recursive: true });
mkdirSync(cacheDir, { recursive: true });

for (const { part, out } of parts) {
  if (only && !only.includes(part)) continue;
  const tmp = `${out}.ascii.stl`;
  const t0 = Date.now();
  execFileSync('openscad', ['-o', tmp, '-D', `part="${part}"`, ...defs, scad], { stdio: 'ignore' });
  writeFileSync(out, asciiToBinaryStl(readFileSync(tmp, 'utf8')));
  rmSync(tmp);
  console.log(`${part.padEnd(22)} -> ${out.replace(root + '/', '')}  (${((Date.now() - t0) / 1000).toFixed(1)} s)`);
}

// The .echo export only evaluates the script, so this is quick.
const echoFile = join(cacheDir, 'mount.echo');
execFileSync('openscad', ['-o', echoFile, ...defs, scad], { stdio: 'ignore' });
const echo = readFileSync(echoFile, 'utf8');
const m = echo.match(/MOUNT_JSON(\{.*\})/);
if (!m) throw new Error('MOUNT_JSON not found in OpenSCAD echo output');
const mount = JSON.parse(m[1].replace(/\\"/g, '"'));
const profile = {
  _comment:
    'Generated by tools/export-stl.mjs from hardware/bat-handle/bat_handle.scad. Millimetres along the handle axis, measured from the bat-frame origin (the junction between the two controller bases). +Y points to the top controller.',
  ...mount,
};
writeFileSync(join(root, 'src/bat/mountProfile.json'), JSON.stringify(profile, null, 2) + '\n');
console.log('mount profile        -> src/bat/mountProfile.json');

function asciiToBinaryStl(text) {
  const facets = [];
  const re = /facet\s+normal\s+(\S+)\s+(\S+)\s+(\S+)\s+outer\s+loop\s+vertex\s+(\S+)\s+(\S+)\s+(\S+)\s+vertex\s+(\S+)\s+(\S+)\s+(\S+)\s+vertex\s+(\S+)\s+(\S+)\s+(\S+)/g;
  let f;
  while ((f = re.exec(text))) facets.push(f.slice(1, 13).map(Number));
  const buf = Buffer.alloc(84 + facets.length * 50);
  buf.write('CricketVR bat handle (OpenSCAD)', 0, 'ascii');
  buf.writeUInt32LE(facets.length, 80);
  facets.forEach((v, i) => {
    const o = 84 + i * 50;
    for (let k = 0; k < 12; k++) buf.writeFloatLE(v[k], o + k * 4);
  });
  return buf;
}
